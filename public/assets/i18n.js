(function() {
  function getLang() {
    return localStorage.getItem('portfolio_lang') || 'en';
  }

  function setLanguage(lang) {
    if (!i18nData[lang]) lang = 'en';
    localStorage.setItem('portfolio_lang', lang);
    document.documentElement.lang = lang;

    const dict = i18nData[lang];

    // Update all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // Update all data-i18n-html elements
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });

    // Update round button label
    document.querySelectorAll('.lang-current-label').forEach(el => {
      el.textContent = lang.toUpperCase();
    });

    // Update active state in dropdown
    document.querySelectorAll('.lang-dropdown-item').forEach(item => {
      const itemLang = item.getAttribute('data-lang');
      const check = item.querySelector('.lang-check');
      if (itemLang === lang) {
        item.classList.add('active');
        if (check) check.style.opacity = '1';
      } else {
        item.classList.remove('active');
        if (check) check.style.opacity = '0';
      }
    });

    window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  }

  
  // Automatic Active Navbar Link Highlighter
  function updateActiveNav() {
    var rawPath = window.location.pathname.replace(/\/$/, '') || '/';
    document.querySelectorAll('.nav-links .nav-link').forEach(function(link) {
      var href = link.getAttribute('href').replace(/\/$/, '') || '/';
      var isActive = false;
      if (rawPath === '/' && href === '/') {
        isActive = true;
      } else if (rawPath !== '/' && href !== '/' && rawPath.startsWith(href)) {
        isActive = true;
      }
      if (isActive) {
        link.classList.add('active');
        link.setAttribute('aria-current', 'page');
      } else {
        link.classList.remove('active');
        link.removeAttribute('aria-current');
      }
    });
  }

  window.addEventListener('DOMContentLoaded', updateActiveNav);
  window.addEventListener('popstate', updateActiveNav);
  setTimeout(updateActiveNav, 50);

  // Dynamic header scroll: transparent at top, solid white when scrolled
  function updateHeaderScroll() {
    var nav = document.querySelector('body > nav, nav[aria-label="Main navigation"], header nav');
    if (!nav) return;
    if (window.scrollY > 30) {
      nav.classList.add('nav-scrolled');
    } else {
      nav.classList.remove('nav-scrolled');
    }
  }
  window.addEventListener('scroll', updateHeaderScroll, { passive: true });
  window.addEventListener('DOMContentLoaded', updateHeaderScroll);
  setTimeout(updateHeaderScroll, 50);

  window.__setLang = setLanguage;

  
  // Music Audio Controller
  var bgAudio = null;
  function getAudio() {
    if (!bgAudio) {
      bgAudio = document.getElementById('site-bg-music');
      if (!bgAudio) {
        bgAudio = document.createElement('audio');
        bgAudio.id = 'site-bg-music';
        bgAudio.src = '/music.mp3';
        bgAudio.preload = 'auto';
        bgAudio.loop = true;
        document.body.appendChild(bgAudio);
      }
      bgAudio.addEventListener('play', function() { updateMusicUI(true); });
      bgAudio.addEventListener('pause', function() { updateMusicUI(false); });
      bgAudio.addEventListener('ended', function() { updateMusicUI(false); });
    }
    return bgAudio;
  }

  function updateMusicUI(isPlaying) {
    var buttons = document.querySelectorAll('.music-toggle-btn');
    buttons.forEach(function(btn) {
      if (isPlaying) {
        btn.classList.add('is-playing');
        btn.setAttribute('aria-label', 'Jeda Musik / Pause Music');
        btn.setAttribute('title', 'Jeda Musik / Pause Music');
      } else {
        btn.classList.remove('is-playing');
        btn.setAttribute('aria-label', 'Putar Musik / Play Music');
        btn.setAttribute('title', 'Putar Musik / Play Music');
      }
    });
  }

  window.__toggleMusic = function(e) {
    if (e) {
      e.stopPropagation();
      e.preventDefault();
    }
    var audio = getAudio();
    if (audio.paused) {
      audio.play().then(function() {
        updateMusicUI(true);
      }).catch(function(err) {
        console.log('Audio playback error:', err);
      });
    } else {
      audio.pause();
      updateMusicUI(false);
    }
  };

  window.__toggleLangDropdown = function(e) {
    if (e) {
      e.stopPropagation();
      e.preventDefault();
    }
    const menus = document.querySelectorAll('.lang-dropdown-menu');
    menus.forEach(menu => {
      menu.classList.toggle('open');
    });
  };

  // Close dropdown on outside click
  document.addEventListener('click', function(e) {
    if (!e.target.closest('.lang-dropdown-container')) {
      document.querySelectorAll('.lang-dropdown-menu.open').forEach(menu => {
        menu.classList.remove('open');
      });
    }
  });

  // Init on load
  function init() {
    const lang = getLang();
    setLanguage(lang);

    // Bind dropdown buttons
    document.querySelectorAll('.lang-dropdown-btn').forEach(btn => {
      btn.onclick = window.__toggleLangDropdown;
    });

    // Bind dropdown item clicks
    document.querySelectorAll('.lang-dropdown-item').forEach(item => {
      item.onclick = function(e) {
        e.stopPropagation();
        const selectedLang = this.getAttribute('data-lang');
        setLanguage(selectedLang);
        document.querySelectorAll('.lang-dropdown-menu.open').forEach(menu => {
          menu.classList.remove('open');
        });
      };
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
